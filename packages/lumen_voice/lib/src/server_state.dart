/// Состояние связи с сервером голоса. «Сервер не отвечает» и «Нет интернета» —
/// разные окна: сервер не всегда работает у Брэда дома.
enum ServerState {
  /// Адрес ещё не задан.
  notSet,
  connected,

  /// Интернет есть, а сервер молчит.
  notResponding,

  /// Нет сети вообще.
  noInternet,

  /// Сервер ответил, но ключ не подошёл.
  wrongKey,
}
